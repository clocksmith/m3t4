const EXPECTED_NAME_SPACE = 2 ** 16;

export const BOT_NAME_SPACE =
  HANDLE_ADJECTIVES.length * HANDLE_NOUNS.length * HANDLE_ENDINGS.length;

if (BOT_NAME_SPACE !== EXPECTED_NAME_SPACE) {
  throw new Error(`bot name space expected ${EXPECTED_NAME_SPACE}, got ${BOT_NAME_SPACE}`);
}

export function generatedBotName(seed: number): string {
  const index = seed >>> 0;
  const adjective = HANDLE_ADJECTIVES[index & 0x3f];
  const noun = HANDLE_NOUNS[(index >>> 6) & 0x3f];
  const ending = HANDLE_ENDINGS[(index >>> 12) & 0x0f];
  return ending ? `${adjective}-${noun}-${ending}` : `${adjective}-${noun}`;
}
